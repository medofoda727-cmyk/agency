"""Build word-timed captions for an episode.
usage: python3 kit/captions.py <episodeDir>
reads  vo/words_raw.json (ElevenLabs scribe), vo/script_compact.txt, vo/timing_words.json, variants.json
writes captions_data.js (CAPTIONS chunks, VO clock) + out/captions_<variant>.srt
"""
import json, re, sys, os
ep = sys.argv[1]; os.chdir(ep)
words = [w for w in json.load(open('vo/words_raw.json'))['words'] if w.get('type', 'word') == 'word' and not w['text'].startswith('[') and not w['text'].endswith(']')]
lines = [re.sub(r'\[[^\]]*\]', '', l).split() for l in open('vo/script_compact.txt') if l.strip()]
T = json.load(open('vo/timing_words.json'))['T']
variants = json.load(open('variants.json'))

# 1) word times on the VO clock: per-line offset so each line starts on its snapped silence
out = []; i = 0
for li, l in enumerate(lines):
    grp = words[i:i + len(l)]; i += len(l)
    off = 0.0 if li == 0 else (T[li] + 0.02) - grp[0]['start']
    nxt = T[li + 1] if li + 1 < len(T) else 1e9
    for w in grp:
        out.append({'w': w['text'], 's': round(w['start'] + off, 3), 'e': round(min(w['end'] + off, nxt - .02), 3), 'line': li})

def clean(w):
    w = w.replace('…', '').rstrip('،.:,')
    return w
PUNCT = ('،', '…', '.', '!', ':', '؟', ',')
# 2) chunks of ≤3 words / ≤20 chars, broken at punctuation and pauses
chunks = []; cur = []
for k, w in enumerate(out):
    cur.append(w)
    last = k == len(out) - 1
    gap = (out[k + 1]['s'] - w['e']) if not last else 9
    chars = sum(len(clean(x['w'])) + 1 for x in cur)
    if last or len(cur) >= 3 or chars > 17 or w['w'].endswith(PUNCT) or gap > .45 or out[k + 1]['line'] != w['line']:
        chunks.append(cur); cur = []
C = []
for n, ch in enumerate(chunks):
    s = ch[0]['s']; e = ch[-1]['e'] + .45
    if n + 1 < len(chunks): e = min(e, chunks[n + 1][0]['s'] - .02)
    C.append({'s': round(s - .05, 3), 'e': round(e, 3), 'words': [{'w': clean(x['w']), 's': x['s'], 'e': x['e']} for x in ch]})
open('captions_data.js', 'w').write('// generated by kit/captions.py — word-timed caption chunks on the VO clock\nconst CAPTIONS = ' + json.dumps(C, ensure_ascii=False) + ';\n')

# 3) SRT per variant (variant clock)
def fmt(t):
    t = max(0, t); h = int(t // 3600); m = int(t % 3600 // 60); s = t % 60
    return f'{h:02d}:{m:02d}:{int(s):02d},{int(round((s - int(s)) * 1000)) % 1000:03d}'
os.makedirs('out', exist_ok=True)
for name, v in variants.items():
    segs = v.get('edl') or [{'a': 0, 'b': v['dur']}]
    rows = []; acc = 0
    for sg in segs:
        for c in C:
            if c['s'] >= sg['a'] - .05 and c['words'][-1]['e'] <= sg['b'] + .05:
                rows.append((acc + max(0, c['s'] - sg['a']), acc + min(c['e'], sg['b']) - sg['a'], ' '.join(x['w'] for x in c['words'])))
        acc += sg['b'] - sg['a']
    rows = [(a, min(b, rows[k + 1][0] - .001) if k + 1 < len(rows) else b, x) for k, (a, b, x) in enumerate(rows)]
    with open(f'out/captions_{name}.srt', 'w') as f:
        for k, (a, b, txt_) in enumerate(rows, 1): f.write(f'{k}\n{fmt(a)} --> {fmt(b)}\n{txt_}\n\n')
    print(name, len(rows), 'captions')
print(len(C), 'chunks')
